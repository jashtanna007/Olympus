-- IMPORTANT:
-- The existing curated All/franchise auction engine is intentionally
-- left unchanged. This preserves the current pending queue, completed
-- results, purse calculations, undo/redo behavior, and manual slot flow.
-- The application renames the existing Male auction to "All".
--
-- Female registrations remain eligible for All whenever they are
-- explicitly loaded into the existing curated All auction flow.
-- ------------------------------------------------------------------

